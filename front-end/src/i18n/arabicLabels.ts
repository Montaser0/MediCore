export function arabicLabel(value: unknown): string {
  if (value === undefined || value === null || value === "") return "—";
  const raw = String(value).trim();
  const key = raw
    .toLowerCase()
    .replace(/[()]/g, "")
    .replace(/[\s.\-]+/g, "_")
    .replace(/_+/g, "_")
    .replace(/^_|_$/g, "");
  return LABELS[key] ?? raw;
}
